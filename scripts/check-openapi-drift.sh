#!/usr/bin/env bash
set -euo pipefail

# CI OpenAPI drift check: verifies that every (method, path) operation registered
# in the runtime of both API services (gateway + ai-gateway) is present in
# swagger-combined.json, and vice-versa. Fails on any mismatch so future custom
# routes cannot silently drift from the spec.
#
# Sources checked:
#   - gateway:    services/gateway/growth/internal/handler/routes.go
#                 services/gateway/growth/growthapi.go (manual /files/upload)
#   - ai-gateway: services/ai-gateway/aiapi/internal/handler/routes.go
#                 services/ai-gateway/aiapi/aiapi.go (manual voice routes)
#
# Usage: bash scripts/check-openapi-drift.sh
# Make:  make check-openapi-drift
#
# Prerequisites: swagger-combined.json must be up to date. Run `make swagger-combined`
# before this check if the contract or custom transports changed.

cd "$(dirname "$0")/.."

SWAGGER_COMBINED="services/gateway/contract/swagger/swagger-combined.json"

GW_ROUTES_GO="services/gateway/growth/internal/handler/routes.go"
GW_MAIN_GO="services/gateway/growth/growthapi.go"
AI_ROUTES_GO="services/ai-gateway/aiapi/internal/handler/routes.go"
AI_MAIN_GO="services/ai-gateway/aiapi/aiapi.go"

for f in "$SWAGGER_COMBINED" "$GW_ROUTES_GO" "$GW_MAIN_GO" "$AI_ROUTES_GO" "$AI_MAIN_GO"; do
    if [ ! -f "$f" ]; then
        echo "ERROR: $f not found."
        exit 1
    fi
done

if ! command -v jq >/dev/null 2>&1; then
    echo "ERROR: jq is required but not installed."
    exit 1
fi

TMPDIR_WORK=$(mktemp -d)
trap 'rm -rf "$TMPDIR_WORK"' EXIT

RUNTIME_OPS="$TMPDIR_WORK/runtime_ops.txt"
SWAGGER_OPS="$TMPDIR_WORK/swagger_ops.txt"

# ---------------------------------------------------------------------------
# Extract (METHOD path) pairs from Go source (routes.go + main.go).
#
# routes.go is generated by goctl and uses the pattern:
#   Method:  http.MethodGet,
#   Path:    "/activity/:id",
# with rest.WithPrefix("/api/v1") after each AddRoutes block.
#
# main.go manually registers custom routes with the same /api/v1 prefix.
#
# Normalization:
#   - http.MethodGet → GET, http.MethodPost → POST, etc.
#   - Prepend /api/v1 to each path.
#   - Convert :param to {param} to match OpenAPI path templating.
# ---------------------------------------------------------------------------
extract_runtime_ops() {
    local file="$1"
    awk '
        /Method:[[:space:]]*http\.Method/ {
            m = $0
            sub(/.*Method:[[:space:]]*http\.Method/, "", m)
            sub(/,.*/, "", m)
            method = toupper(m)
        }
        /Path:[[:space:]]*"/ {
            p = $0
            sub(/.*Path:[[:space:]]*"/, "", p)
            sub(/".*/, "", p)
            gsub(/:[a-zA-Z_][a-zA-Z0-9_]*/, "{&}", p)
            gsub(/:/, "", p)
            if (method != "" && p != "") {
                printf "%s /api/v1%s\n", method, p
                method = ""
            }
        }
    ' "$file"
}

{
    extract_runtime_ops "$GW_ROUTES_GO"
    extract_runtime_ops "$GW_MAIN_GO"
    extract_runtime_ops "$AI_ROUTES_GO"
    extract_runtime_ops "$AI_MAIN_GO"
} | sort -u > "$RUNTIME_OPS"

# ---------------------------------------------------------------------------
# Extract (METHOD path) pairs from swagger-combined.json (OpenAPI 3.0).
# ---------------------------------------------------------------------------
jq -r '
    .paths | to_entries[] |
    .key as $path |
    .value | to_entries[] |
    select(.key | test("^(get|post|put|delete|patch)$")) |
    (.key | ascii_upcase) + " " + $path
' "$SWAGGER_COMBINED" | sort -u > "$SWAGGER_OPS"

# ---------------------------------------------------------------------------
# Compare: report operations in runtime but not in swagger (undocumented),
# and operations in swagger but not in runtime (stale).
# ---------------------------------------------------------------------------
UNDocumented=$(comm -23 "$RUNTIME_OPS" "$SWAGGER_OPS" | wc -l | tr -d ' ')
STALE=$(comm -13 "$RUNTIME_OPS" "$SWAGGER_OPS" | wc -l | tr -d ' ')

EXIT_CODE=0

if [ "$UNDocumented" -gt 0 ]; then
    echo "ERROR: $UNDocumented runtime operation(s) are NOT documented in swagger-combined.json:"
    comm -23 "$RUNTIME_OPS" "$SWAGGER_OPS" | sed 's/^/  /'
    echo ""
    echo "Fix: add the missing route to the appropriate contract (gateway or ai-gateway)"
    echo "and run make generate-api (or generate-ai-api) + make swagger-combined."
    echo "For custom transports, update services/gateway/contract/swagger/custom-transports.yaml."
    EXIT_CODE=1
fi

if [ "$STALE" -gt 0 ]; then
    echo "ERROR: $STALE swagger-combined.json operation(s) are NOT registered in any runtime:"
    comm -13 "$RUNTIME_OPS" "$SWAGGER_OPS" | sed 's/^/  /'
    echo ""
    echo "Fix: regenerate the spec (make swagger-combined) or remove the stale operation from the contract."
    EXIT_CODE=1
fi

if [ "$EXIT_CODE" -eq 0 ]; then
    RUNTIME_COUNT=$(wc -l < "$RUNTIME_OPS" | tr -d ' ')
    SWAGGER_COUNT=$(wc -l < "$SWAGGER_OPS" | tr -d ' ')
    echo "OpenAPI drift check passed: $RUNTIME_COUNT runtime operation(s) match swagger-combined.json ($SWAGGER_COUNT operation(s))."
fi

exit $EXIT_CODE
